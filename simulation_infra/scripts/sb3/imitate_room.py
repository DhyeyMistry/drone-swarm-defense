"""Fit the existing actor to successful original/mirrored full-room examples.

This is supervised imitation, not PPO on fabricated mirrored transitions.
The resulting network retains the existing 200-input/5-output architecture.
"""

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np
import torch
from stable_baselines3 import PPO


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkpoint", required=True)
    parser.add_argument("--dataset", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--epochs", type=int, default=20)
    parser.add_argument("--learning-rate", type=float, default=1e-4)
    parser.add_argument("--batch-size", type=int, default=1024)
    parser.add_argument("--seed", type=int, default=47)
    args = parser.parse_args()
    out, parent, dataset = Path(args.out), Path(args.checkpoint).resolve().parent, Path(args.dataset)
    out.mkdir(parents=True, exist_ok=False)
    collection = json.loads(dataset.with_name("collection.json").read_text())
    checkpoint_hash = hashlib.sha256(Path(args.checkpoint).read_bytes()).hexdigest()
    numbered = re.fullmatch(r"model_(\d+)_steps", Path(args.checkpoint).stem)
    norm_name = f"model_vecnormalize_{numbered.group(1)}_steps.pkl" if numbered else "model_vecnormalize.pkl"
    if collection["teacher_sha256"] != checkpoint_hash:
        raise ValueError("Dataset was generated by a different teacher checkpoint")
    if collection["normalizer_sha256"] != hashlib.sha256((parent / norm_name).read_bytes()).hexdigest():
        raise ValueError("Dataset and checkpoint normalization statistics differ")
    shutil.copytree(parent / "params", out / "params")
    shutil.copytree(parent / "assets", out / "assets")
    shutil.copy2(parent / norm_name, out / "model_vecnormalize.pkl")
    shutil.copy2(out / "params/run.json", out / "params/teacher_run.json")
    shutil.copy2(out / "params/env.yaml", out / "params/teacher_env.yaml")
    env_text = (out / "params/env.yaml").read_text()
    (out / "params/env.yaml").write_text(re.sub(
        r"(?m)^(spawn_short_fraction|spawn_hover_fraction):.*$", r"\1: 0.0", env_text))
    run = json.loads((out / "params/run.json").read_text())
    # Delivered imitation candidates default to complete missions, never replay starts.
    run["env"]["spawn_short_fraction"] = run["env"]["spawn_hover_fraction"] = 0.
    rng = np.random.default_rng(args.seed)
    model = PPO.load(args.checkpoint, device="cuda")
    # PPO.load restores the parent's seed; apply the requested imitation seed afterward.
    model.seed = args.seed
    model.set_random_seed(args.seed)
    model.policy.set_training_mode(True)
    data = np.load(dataset)
    groups = np.unique(data["groups"])
    rng.shuffle(groups)
    if len(groups) < 10:
        raise ValueError("Need at least ten successful trajectories for a grouped validation split")
    heldout = groups[:max(2, len(groups) // 5)]
    is_validation = np.isin(data["groups"], heldout)
    train_ids = torch.as_tensor(np.flatnonzero(~is_validation), device=model.device)
    validation_ids = torch.as_tensor(np.flatnonzero(is_validation), device=model.device)
    x = torch.as_tensor(data["observations"], device=model.device)
    y = torch.as_tensor(data["actions"], device=model.device)
    actor = list(model.policy.mlp_extractor.policy_net.parameters()) + list(model.policy.action_net.parameters())
    optimizer = torch.optim.Adam(actor, lr=args.learning_rate)
    # PPO should create fresh actor moments if this imitation candidate is resumed.
    for parameter in actor:
        model.policy.optimizer.state.pop(parameter, None)

    def predict(indices):
        features = model.policy.extract_features(x[indices])
        return model.policy.action_net(model.policy.mlp_extractor.forward_actor(features))

    def score(indices):
        with torch.no_grad():
            error = predict(indices) - y[indices]
            return {"mse": float(error.square().mean()),
                    "per_action_mse": error.square().mean(0).cpu().tolist()}

    history = [{"epoch": 0, "training": score(train_ids), "validation": score(validation_ids)}]
    print(json.dumps(history[-1]), flush=True)
    for epoch in range(1, args.epochs + 1):
        order = train_ids[torch.randperm(len(train_ids), device=model.device)]
        for batch in order.split(args.batch_size):
            loss = (predict(batch) - y[batch]).square().mean()
            optimizer.zero_grad()
            loss.backward()
            torch.nn.utils.clip_grad_norm_(actor, 1.)
            optimizer.step()
        row = {"epoch": epoch, "training": score(train_ids), "validation": score(validation_ids)}
        history.append(row)
        print(json.dumps(row), flush=True)
        if epoch in (5, 10, 20, 50, args.epochs):
            model.save(out / f"actor_epoch{epoch:02d}.zip")
    model.save(out / "model.zip")
    repo = Path(__file__).resolve().parents[3]
    metadata = {"method": "supervised actor imitation with paired reflection examples",
                "parent_checkpoint": str(Path(args.checkpoint).resolve()),
                "parent_sha256": checkpoint_hash,
                "dataset_sha256": hashlib.sha256(dataset.read_bytes()).hexdigest(),
                "git_commit": subprocess.check_output(["git", "-C", str(repo), "rev-parse", "HEAD"], text=True).strip(),
                "argv": sys.orig_argv, "heldout_trajectory_groups": heldout.tolist(),
                "torch_seed": torch.initial_seed(),
                "train_examples": len(train_ids), "validation_examples": len(validation_ids),
                "history": history, "qualification": "requires evaluation in the actual unmodified room"}
    run["imitation"] = metadata
    (out / "params/run.json").write_text(json.dumps(run, indent=2) + "\n")
    (out / "params/imitation.json").write_text(json.dumps(metadata, indent=2) + "\n")
    shutil.copy2(__file__, out / "params/imitation_source.py")
    shutil.copy2(Path(__file__).with_name("collect_room_demonstrations.py"), out / "params/collection_source.py")
    shutil.copy2(repo / "simulation_infra/source/action_space_kit/action_space_kit/rl/symmetry.py",
                 out / "params/symmetry_source.py")
    print(f"IMITATION COMPLETE: {out}", flush=True)


if __name__ == "__main__":
    main()
